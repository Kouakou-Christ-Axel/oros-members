export type IconName = keyof typeof GLYPHS;

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, "name"> {
  name: IconName;
  size?: number;
  strokeWidth?: number;
  title?: string;
}

export function Icon({ name, size = 16, strokeWidth, title, ...rest }: IconProps) {
  const Glyph = GLYPHS[name];
  if (!Glyph) {
    if (typeof console !== "undefined") console.warn(`Icon: unknown glyph "${name}"`);
    return null;
  }
  const sw = strokeWidth ?? (size <= 13 ? 2.25 : size >= 32 ? 1.75 : 2);
  return (
    <Glyph
      width={size}
      height={size}
      strokeWidth={sw}
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
      style={{ flexShrink: 0, display: "block", ...rest.style }}
      {...rest}
    >
      {title ? <title>{title}</title> : null}
    </Glyph>
  );
}
